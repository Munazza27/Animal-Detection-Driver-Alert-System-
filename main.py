"""
main.py
-------
Entry point for Person 1's module. Run detection on a video file,
save an annotated output video (for quick visual sanity-check),
and export a per-frame JSON log that Person 2 can consume directly
to build the risk logic on top of.
 
Usage:
    python main.py --video data/raw_videos/sample.mp4
    python main.py --video data/raw_videos/sample.mp4 --output output/annotated.mp4
 
If no --video is given, it falls back to a small synthetic test
video (data/raw_videos/synthetic_test.mp4) generated by
tests/make_synthetic_video.py, purely so you can confirm the
pipeline runs end-to-end before you have real footage.
"""
 
import argparse
import json
import os
import time
 
import cv2 
 
from src.detector import AnimalDetector
from src.utils import draw_detections
from src.tracker import smooth_detections
 
 
def run_on_video(video_path: str, output_video_path: str, output_json_path: str):
    if not os.path.exists(video_path):
        raise FileNotFoundError(
            f"Video not found: {video_path}\n"
            f"Drop a test clip into data/raw_videos/ or run "
            f"tests/make_synthetic_video.py to generate a dummy test video."
        )
 
    detector = AnimalDetector()
 
    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        raise RuntimeError(f"Could not open video: {video_path}")
 
    fps = cap.get(cv2.CAP_PROP_FPS) or 25
    frame_w = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    frame_h = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
 
    os.makedirs(os.path.dirname(output_video_path), exist_ok=True)
    os.makedirs(os.path.dirname(output_json_path), exist_ok=True)
 
    fourcc = cv2.VideoWriter_fourcc(*"mp4v")
    writer = cv2.VideoWriter(output_video_path, fourcc, fps, (frame_w, frame_h))
 
    all_frame_logs = []
    frame_index = 0
    start_time = time.time()
 
    while True:
        ret, frame = cap.read()
        if not ret:
            break
 
        detections = detector.detect(frame)
 
        annotated_frame = draw_detections(frame.copy(), detections)
        writer.write(annotated_frame)
 
        all_frame_logs.append({
            "frame_index": frame_index,
            "timestamp_sec": round(frame_index / fps, 3),
            "detections": detections,
        })
 
        frame_index += 1
        if frame_index % 30 == 0:
            print(f"Processed {frame_index} frames...")
 
    cap.release()
    writer.release()
 
    elapsed = time.time() - start_time
    print(f"\nDone. Processed {frame_index} frames in {elapsed:.1f}s "
          f"({frame_index / elapsed:.1f} FPS average).")
    print(f"Annotated video saved to: {output_video_path}")
    
    with open(output_json_path, "w") as f:
        json.dump(all_frame_logs, f, indent=2)
    print(f"Per-frame detection log saved to: {output_json_path}")

    events = smooth_detections(all_frame_logs, fps=fps)
    events_path = output_json_path.replace(".json", "_events.json")
    with open(events_path, "w") as f:
        json.dump(events, f, indent=2)
    print(f"Smoothed presence events saved to: {events_path}")
    print(f"({len(events)} distinct animal presence event(s) detected)")

    return all_frame_logs, events
 
 
if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Run animal detection on a video file.")
    parser.add_argument(
        "--video", type=str,
        default="data/raw_videos/synthetic_test.mp4",
        help="Path to input video file"
    )
    parser.add_argument(
        "--output", type=str,
        default="output/annotated_output.mp4",
        help="Path to save annotated output video"
    )
    parser.add_argument(
        "--json", type=str,
        default="output/detections.json",
        help="Path to save per-frame detection JSON log"
    )
    args = parser.parse_args()
 
    run_on_video(args.video, args.output, args.json)
 